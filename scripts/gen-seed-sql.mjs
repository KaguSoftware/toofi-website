#!/usr/bin/env node
/**
 * Generates from data/seed/{users,pages,blocks}.json:
 *   supabase/seed.sql              pages + blocks only (no credentials; runs on `supabase db reset`)
 *   supabase/seed-users.local.sql  demo auth users, password "password" (NOT in config.toml;
 *                                  guarded; LOCAL ONLY — see docs/SUPABASE.md)
 * Deterministic (no clocks, no randomness): re-running yields an identical file.
 *
 *   npm run db:seed-sql
 *
 * Users are inserted into auth.users/auth.identities, which GoTrue accepts for email+password.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const readJson = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

const users = readJson("data/seed/users.json");
const pages = readJson("data/seed/pages.json");
const blocks = readJson("data/seed/blocks.json");

const NL = String.fromCharCode(10);
const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const ts = (v) => (v ? `${q(v)}::timestamptz` : "null");
const SEED_TS = "2026-11-14T00:00:00.000Z";

/** Stable uuid from scope+key so block ids never change between generations. */
function blockId(scope, key) {
  const h = createHash("sha1").update(`sawad-seed-block:${scope}:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const out = [];
out.push(`-- GENERATED by scripts/gen-seed-sql.mjs from data/seed/*.json — do not edit by hand.
-- Content only (pages + blocks); contains no credentials.
`);

const usersOut = [];
usersOut.push(`-- GENERATED by scripts/gen-seed-sql.mjs from data/seed/users.json — do not edit by hand.
-- DEMO USERS WITH THE PASSWORD "password". LOCAL SUPABASE ONLY. Never run against a hosted project.
-- Not part of config.toml sql_paths: apply on purpose, e.g.
--   PGOPTIONS="-c sawad.allow_demo_users=on" psql "postgresql://postgres:postgres@127.0.0.1:54322/postgres" -f supabase/seed-users.local.sql

do $guard$
begin
  if coalesce(current_setting('sawad.allow_demo_users', true), '') <> 'on' then
    raise exception 'Refusing to create demo users: set sawad.allow_demo_users=on (local databases only)';
  end if;
  -- Second barrier: a database that already has real accounts is not a throwaway one.
  if exists (select 1 from auth.users where email not in (${users.map((u) => q(u.email)).join(", ")})) then
    raise exception 'Refusing to create demo users: auth.users already contains non-demo accounts';
  end if;
end
$guard$;
`);

// ── auth users (+ identities) ──
const o = usersOut;
o.push("-- ── sample auth users ──");
for (const u of users) {
  o.push(`insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
) values (
  '00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)},
  extensions.crypt('password', extensions.gen_salt('bf')), ${ts(u.createdAt ?? SEED_TS)},
  '{"provider":"email","providers":["email"]}'::jsonb, ${j({ name: u.name })}, ${ts(u.createdAt ?? SEED_TS)}, ${ts(u.createdAt ?? SEED_TS)},
  '', '', '', ''
) on conflict (id) do nothing;`);
  o.push(`insert into auth.identities (id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at)
values (
  ${q(u.id)}, ${q(u.id)}, ${q(u.id)}, 'email',
  ${j({ sub: u.id, email: u.email, email_verified: true, phone_verified: false })},
  ${ts(u.createdAt ?? SEED_TS)}, ${ts(u.createdAt ?? SEED_TS)}, ${ts(u.createdAt ?? SEED_TS)}
) on conflict (provider_id, provider) do nothing;`);
}
o.push("");
o.push("-- The auth trigger created profiles as 'member'; apply the seeded roles + names.");
for (const u of users) {
  o.push(`update public.profiles set role = ${q(u.role)}::public.app_role, name = ${q(u.name)} where id = ${q(u.id)};`);
}

// ── pages ──
out.push("", "-- ── pages ──");
for (const p of pages) {
  out.push(`insert into public.pages (id, slug, title, template, status, seo, created_at, updated_at, published_at)
values (${q(p.id)}, ${q(p.slug)}, ${q(p.title)}, ${q(p.template)}, ${q(p.status)}, ${j(p.seo ?? {})}, ${ts(p.createdAt ?? SEED_TS)}, ${ts(p.updatedAt ?? SEED_TS)}, ${ts(p.publishedAt)})
on conflict (id) do update set slug = excluded.slug, title = excluded.title, template = excluded.template,
  status = excluded.status, seo = excluded.seo, published_at = excluded.published_at;`);
}

// ── blocks (published, no draft — same as LocalProvider.seedStore) ──
out.push("", "-- ── content blocks ──");
const sorted = [...blocks].sort((a, b) => (a.scope + "\0" + a.key).localeCompare(b.scope + "\0" + b.key));
for (const b of sorted) {
  const pageId = b.scope === "global" ? "null" : q(b.scope);
  out.push(`insert into public.content_blocks (id, page_id, key, type, draft, published)
values (${q(blockId(b.scope, b.key))}, ${pageId}, ${q(b.key)}, ${q(b.type)}, null, ${j(b.value)})
on conflict (scope, key) do update set type = excluded.type, published = excluded.published, draft = null;`);
}
out.push("");

usersOut.push("");
writeFileSync(join(root, "supabase", "seed.sql"), out.join(NL), "utf8");
writeFileSync(join(root, "supabase", "seed-users.local.sql"), usersOut.join(NL), "utf8");
console.log(`supabase/seed.sql: ${pages.length} pages, ${blocks.length} blocks; supabase/seed-users.local.sql: ${users.length} users`);
