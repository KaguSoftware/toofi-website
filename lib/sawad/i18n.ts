/**
 * Locale routing + copy. English lives at /…, Arabic at /ar/…, as separate CMS pages
 * that share templates. These strings are the template fallbacks: editors can override
 * the editable ones per page in edit mode.
 */

export const LOCALES: Locale[] = ["en", "ar"];

export function localeFromPath(path: string): Locale {
  return path === "/ar" || path.startsWith("/ar/") ? "ar" : "en";
}

export function dirOf(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

/** Strip the locale prefix: "/ar/residences" → "/residences", "/ar" → "/". */
export function basePath(path: string): string {
  if (path === "/ar") return "/";
  return path.startsWith("/ar/") ? path.slice(3) : path;
}

/** "/residences" + ar → "/ar/residences"; "/" + ar → "/ar". */
export function localizedPath(path: string, locale: Locale): string {
  const base = basePath(path);
  if (locale === "en") return base;
  return base === "/" ? "/ar" : `/ar${base}`;
}

